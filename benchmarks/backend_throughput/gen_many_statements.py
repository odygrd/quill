"""Generates quill_backend_throughput.cpp and quill_backend_throughput_many_statements.cpp.

The other backend throughput benchmarks cycle between a few log statements. An application has
hundreds, with different format strings, argument types and source locations, logged in no fixed
order. These two benchmarks log the same NUM_STATEMENTS distinct statements in the same fixed
pseudo-random order, so that an optimization can be measured the way AGENTS.md asks before it is
kept. They differ only in the pattern and the log file.
"""
import random
from pathlib import Path

# Output file, log file, comment and PatternFormatterOptions of each benchmark
BENCHMARKS = [
    ("quill_backend_throughput.cpp", "quill_backend_total_time.log",
     "A custom pattern with the time of day in nanoseconds",
     'quill::PatternFormatterOptions{\n'
     '      "%(time) [%(thread_id)] %(short_source_location) %(log_level) %(message)", "%H:%M:%S.%Qns",\n'
     '      quill::Timezone::LocalTime, false}'),
    ("quill_backend_throughput_many_statements.cpp", "quill_backend_total_time_many_statements.log",
     "The default pattern, as most applications use it", "quill::PatternFormatterOptions{}"),
]
RNG_SEED = 1337
NUM_STATEMENTS = 256

WORDS = ["order", "quantity", "price", "venue", "side", "sequence", "latency", "bytes", "session",
         "symbol", "fill", "cancel", "retry", "depth", "spread", "bid", "ask", "position", "risk",
         "limit", "book", "level", "message", "connection", "gap", "count", "worker", "request"]
PREFIXES = ["", "Event ", "Order update ", "Risk check ", "Market data ", "Session "]
SEPARATORS = [" ", ", ", " | "]

# Arguments of the types an application commonly logs, all derived from the iteration
ARGUMENTS = ["iteration", "-static_cast<int64_t>(iteration)", "static_cast<double>(iteration) / 8",
             "symbols[iteration & 7]", "static_cast<char>('A' + (iteration % 26))",
             "static_cast<uint32_t>(iteration * 3)"]


def generate_statements():
    rng = random.Random(RNG_SEED)
    statements = []

    for index in range(NUM_STATEMENTS):
        num_args = rng.randint(1, 5)
        fields = [f"{rng.choice(WORDS)}: {{}}" for _ in range(num_args)]
        message = f"{rng.choice(PREFIXES)}#{index} {rng.choice(SEPARATORS).join(fields)}"
        args = ", ".join(rng.choice(ARGUMENTS) for _ in range(num_args))
        statements.append(f'    case {index}:\n      LOG_INFO(logger, "{message}", {args});\n      break;')

    return statements


def write_file(output_file, log_file, pattern_comment, pattern_options, statements):
    cases = "\n".join(statements)
    Path(__file__).with_name(output_file).write_text(f'''// Generated by gen_many_statements.py, do not edit
#include <chrono>
#include <cstdint>
#include <iostream>
#include <vector>

#include "quill/Backend.h"
#include "quill/Frontend.h"
#include "quill/LogMacros.h"
#include "quill/sinks/FileSink.h"

static constexpr size_t total_iterations = 4'000'000;

/**
 * The backend worker just spins, so we just measure the total time elapsed for total_iterations.
 * {NUM_STATEMENTS} distinct log statements with 1 to 5 arguments are logged in a fixed pseudo-random
 * order, as an application logs many different statements rather than repeating a few
 */
int main()
{{
  // main thread affinity - pinning can legitimately fail (e.g. Apple Silicon does not support
  // the affinity policy); warn and continue instead of terminating the benchmark
#if defined(QUILL_NO_EXCEPTIONS)
  quill::detail::set_cpu_affinity({{1}});
#else
  try
  {{
    quill::detail::set_cpu_affinity({{1}});
  }}
  catch (std::exception const& e)
  {{
    std::cerr << "Failed to set cpu affinity: " << e.what() << std::endl;
  }}
#endif

  quill::BackendOptions backend_options;
  backend_options.cpu_affinity = {{5}};
  backend_options.sleep_duration = std::chrono::nanoseconds{{0}};
  backend_options.log_timestamp_ordering_grace_period = std::chrono::microseconds{{1}};

  // Start the logging backend thread and give it some time to init
  quill::Backend::start(backend_options);

  // Create a file sink to write to a file
  std::shared_ptr<quill::Sink> file_sink = quill::Frontend::create_or_get_sink<quill::FileSink>(
    "{log_file}",
    []()
    {{
      quill::FileSinkConfig cfg;
      cfg.set_open_mode('w');
      return cfg;
    }}(),
    quill::FileEventNotifier{{}});

  // {pattern_comment}
  quill::Logger* logger = quill::Frontend::create_or_get_logger(
    "bench_logger", std::move(file_sink), {pattern_options});

  static char const* const symbols[8] = {{"AAPL", "MSFT", "ES", "NQ", "CL", "ZN", "GC", "EURUSD"}};

  // The order of the statements, chosen before the timing starts
  std::vector<uint8_t> order(65536);
  uint32_t state{{2463534242u}};
  for (uint8_t& statement : order)
  {{
    state ^= state << 13;
    state ^= state >> 17;
    state ^= state << 5;
    statement = static_cast<uint8_t>(state % {NUM_STATEMENTS});
  }}

  LOG_INFO(logger, "preallocate");
  logger->flush_log(0);

  // start counting the time until backend worker finishes
  auto const start_time = std::chrono::steady_clock::now();
  for (size_t iteration = 0; iteration < total_iterations; ++iteration)
  {{
    switch (order[iteration & (order.size() - 1)])
    {{
{cases}
    default:
      break;
    }}
  }}

  // block until all messages are flushed
  logger->flush_log(0);

  auto const end_time = std::chrono::steady_clock::now();
  auto const delta = end_time - start_time;
  auto delta_d = std::chrono::duration_cast<std::chrono::duration<double>>(delta).count();

  std::cout << fmtquill::format(
                 "Throughput is {{:.2f}} million msgs/sec average, total time elapsed: {{}} ms for {{}} "
                 "log messages \\n",
                 total_iterations / delta_d / 1e6,
                 std::chrono::duration_cast<std::chrono::milliseconds>(delta).count(), total_iterations)
            << std::endl;
}}
''')


if __name__ == "__main__":
    statements = generate_statements()
    for output_file, log_file, pattern_comment, pattern_options in BENCHMARKS:
        write_file(output_file, log_file, pattern_comment, pattern_options, statements)
